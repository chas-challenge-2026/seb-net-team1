using System.Net;
using System.Net.Http.Headers;
using System.Net.Http.Json;
using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.Mvc.Testing;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.DependencyInjection.Extensions;
using Microsoft.Extensions.Logging;
using Npgsql;
using SebPortal.Api.Auth;
using SebPortal.Api.Data;
using SebPortal.Api.Models;
using SebPortal.Api.Signing;

namespace SebPortal.Api.Tests;

/// <summary>Proves recipient/audit atomicity in a private schema inside disposable test PostgreSQL.</summary>
public sealed class RecipientAuditAtomicityIntegrationTests(PostgreSqlFixture postgres)
    : IClassFixture<PostgreSqlFixture>
{
    [Theory]
    [InlineData(false, HttpStatusCode.Created)]
    [InlineData(true, HttpStatusCode.InternalServerError)]
    public async Task CreateRecipient_CommitsRecipientAndAuditTogetherOrRollsBackBoth(
        bool failSigning, HttpStatusCode expected)
    {
        var schema = $"recipient_atomicity_{Guid.NewGuid():N}";
        await using var administrativeConnection = new NpgsqlConnection(postgres.ConnectionString);
        await administrativeConnection.OpenAsync();
        await ExecuteAsync(administrativeConnection, $"CREATE SCHEMA {schema}");

        try
        {
            var scopedConnectionString = new NpgsqlConnectionStringBuilder(postgres.ConnectionString)
            {
                SearchPath = schema
            }.ConnectionString;
            using var baseFactory = new PostgreSqlPaymentApiFactory(scopedConnectionString);
            using var factory = baseFactory.WithWebHostBuilder(builder =>
            {
                builder.UseEnvironment("Development");
                builder.ConfigureLogging(logging => logging.ClearProviders());
                builder.ConfigureServices(services =>
                {
                    if (failSigning)
                    {
                        services.RemoveAll<IAuditSigner>();
                        services.AddSingleton<IAuditSigner, FailingSigner>();
                    }
                });
            });

            // Generate the mapped schema explicitly, avoiding EnsureCreated's check for
            // unrelated tables in another schema. All unqualified tables use SearchPath.
            using (var scope = factory.Services.CreateScope())
            {
                var db = scope.ServiceProvider.GetRequiredService<SebDbContext>();
                await db.Database.ExecuteSqlRawAsync(db.Database.GenerateCreateScript());
                db.Tenants.Add(new Tenant { Id = 1, Name = "Recipient atomicity tenant" });
                db.Users.Add(new User
                {
                    Id = 1, TenantId = 1, Name = "Recipient creator",
                    Email = "recipient-atomicity@example.invalid", Role = UserRoles.Initiator
                });
                await db.SaveChangesAsync();
            }

            using var client = factory.CreateClient(new WebApplicationFactoryClientOptions
            {
                BaseAddress = new Uri("https://localhost"), AllowAutoRedirect = false
            });
            using (var scope = factory.Services.CreateScope())
            {
                var token = scope.ServiceProvider.GetRequiredService<JwtTokenService>()
                    .GenerateToken(1, 1, "recipient-atomicity@example.invalid", UserRoles.Initiator, "Recipient creator");
                client.DefaultRequestHeaders.Authorization = new AuthenticationHeaderValue("Bearer", token);
            }

            using var response = await client.PostAsJsonAsync("/api/recipients", new
            {
                name = "Atomic recipient", iban = "SE4550000000054910000099", demoConfirmed = true
            });
            Assert.Equal(expected, response.StatusCode);

            using var verificationScope = factory.Services.CreateScope();
            var verificationDb = verificationScope.ServiceProvider.GetRequiredService<SebDbContext>();
            var recipients = await verificationDb.Recipients.AsNoTracking().ToListAsync();
            var auditEntries = await verificationDb.AuditEntries.AsNoTracking().ToListAsync();
            if (failSigning)
            {
                Assert.Empty(recipients);
                Assert.Empty(auditEntries);
            }
            else
            {
                var recipient = Assert.Single(recipients);
                Assert.Equal("Atomic recipient", recipient.Name);
                Assert.Equal("SE4550000000054910000099", recipient.Iban);
                RecipientsApiIntegrationTests.AssertSimulatedAudit(Assert.Single(auditEntries), recipient.Id);
            }
        }
        finally
        {
            // The name above is generated by this test, and this connection belongs
            // to the disposable Testcontainers fixture, never the user's database.
            await ExecuteAsync(administrativeConnection, $"DROP SCHEMA {schema} CASCADE");
        }
    }

    private static async Task ExecuteAsync(NpgsqlConnection connection, string sql)
    {
        await using var command = new NpgsqlCommand(sql, connection);
        await command.ExecuteNonQueryAsync();
    }

    private sealed class FailingSigner : IAuditSigner
    {
        public string Sign(string canonicalJson) =>
            throw new InvalidOperationException("Recipient audit signing failed on purpose.");

        public bool Verify(string canonicalJson, string signature) => false;
    }
}
